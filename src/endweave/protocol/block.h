namespace bp = bedrock::protocol;

namespace endweave {

/** The tag a generated record holds as SNBT, or an empty one where the record leaves it out. */
template <class T>
T parseSnbt(std::string_view snbt)
{
    if (snbt.empty()) {
        return {};
    }
    auto tag = TagParser::parseTag(snbt);
    auto *value = tag ? tag->get_if<T>() : nullptr;
    return value != nullptr ? std::move(*value) : T{};
}

/** How one block type becomes the other version's across a hop, in SNBT: `states` lists every value
 * of each of its states, so every one of its blocks can be numbered, `add` the states it gains and
 * `remove` the ones it loses. Generated by tools/generate_mappings.py. */
struct BlockStateUpdate {
    std::string_view name;
    std::string_view states = {};
    std::string_view rename = {};
    std::string_view add = {};
    std::string_view remove = {};
};

namespace detail {

inline void writeString(bp::BinaryWriter &dos, std::string_view value)
{
    dos.write<std::int16_t>(value.size());
    dos.writeRawBytes(value);
}

/** BDS NbtIo::write into a StringByteOutput: little-endian with fixed-width numbers and string
 * lengths, where bp::nbt writes the network form. Block states only hold these four types. */
inline void writeTag(bp::BinaryWriter &dos, const bp::Tag &tag)
{
    tag.visit([&](const auto &payload) {
        using T = std::decay_t<decltype(payload)>;
        if constexpr (std::is_same_v<T, bp::ByteTag>) {
            dos.write<std::int8_t>(payload.value());
        }
        else if constexpr (std::is_same_v<T, bp::IntTag>) {
            dos.write<std::int32_t>(payload.value());
        }
        else if constexpr (std::is_same_v<T, bp::StringTag>) {
            writeString(dos, payload.value());
        }
        else if constexpr (std::is_same_v<T, bp::CompoundTag>) {
            for (const auto &[name, child] : payload) {
                dos.write<std::uint8_t>(static_cast<std::uint8_t>(child.type()));
                writeString(dos, name);
                writeTag(dos, child);
            }
            dos.write<std::uint8_t>(static_cast<std::uint8_t>(bp::nbt::Type::End));
        }
    });
}

} // namespace detail

/** BDS Block::computeRawSerializationIdHashForNetwork: FNV-1a over the block's name and states as
 * NbtIo::write puts them into a StringByteOutput. */
inline std::uint32_t computeRawSerializationIdHashForNetwork(std::string_view name, const bp::CompoundTag &states)
{
    const bp::CompoundTag tag{{"name", bp::StringTag{std::string(name)}}, {"states", states}};
    std::string buffer;
    bp::BinaryWriter dos{buffer};
    dos.write<std::uint8_t>(static_cast<std::uint8_t>(bp::nbt::Type::Compound));
    detail::writeString(dos, "");
    detail::writeTag(dos, tag);
    std::uint32_t hash = 0x811C9DC5;
    for (const char byte : buffer) {
        hash = (hash ^ static_cast<std::uint8_t>(byte)) * 0x01000193;
    }
    return hash;
}

/** Calls `visit(states)` for every combination of the values `states` lists, a list per state. */
template <class Visit>
void forEachState(const bp::CompoundTag &states, Visit &&visit)
{
    std::vector<std::pair<const std::string *, const bp::ListTag *>> lists;
    for (const auto &[name, values] : states) {
        const auto *list = values.get_if<bp::ListTag>();
        if (list == nullptr || list->size() == 0) {
            return;
        }
        lists.emplace_back(&name, list);
    }
    std::vector<std::size_t> value(lists.size());
    while (true) {
        bp::CompoundTag tag;
        for (std::size_t i = 0; i < lists.size(); ++i) {
            tag.insert_or_assign(*lists[i].first, (*lists[i].second)[value[i]]);
        }
        visit(tag);

        std::size_t i = 0;
        while (i < value.size() && ++value[i] == lists[i].second->size()) {
            value[i++] = 0;
        }
        if (i == value.size()) {
            return;
        }
    }
}

/** Calls `visit(states, updated)` for every block of `update`'s type, with its states before the hop
 * and after it. */
template <class Visit>
void forEachBlock(const BlockStateUpdate &update, Visit &&visit)
{
    const auto add = parseSnbt<bp::CompoundTag>(update.add);
    const auto remove = parseSnbt<bp::ListTag>(update.remove);
    forEachState(parseSnbt<bp::CompoundTag>(update.states), [&](const bp::CompoundTag &states) {
        bp::CompoundTag updated = states;
        for (const auto &[state, tag] : add) {
            updated.insert_or_assign(state, tag);
        }
        for (const auto &state : remove) {
            if (const auto *name = state.get_if<bp::StringTag>()) {
                updated.erase(name->value());
            }
        }
        visit(states, updated);
    });
}

} // namespace endweave
