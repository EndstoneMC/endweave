/** The blocks of one type that are the same to the blocks beside them: what BDS reads off a block
 * when it works out a neighbour's connections. `states` lists their values in SNBT, the masks are
 * by BDS `Facing`, and `should_connect_to_redstone` by `Direction`, south, west, north, east, then
 * any. Generated by tools/generate_block_states.py. */
struct NeighborBlock {
    std::string_view name;
    std::string_view states = {};
    // BlockConnectionRuleComponent, and Block::getConnectionID.
    std::optional<std::uint8_t> connections_from = {};
    std::uint8_t enabled_directions = 0;
    std::optional<std::uint8_t> connection_id = {};
    std::uint8_t flame_odds = 0;
    // BlockRedstoneComponent, BlockRedstoneProducerComponent, and BlockType's redstone virtuals.
    bool redstone_conductor = false;
    std::optional<std::uint8_t> redstone_producer_faces = {};
    std::uint8_t should_connect_to_redstone = 0;
    std::uint8_t full_support_faces = 0;
    bool signal_source = false;
    bool consumer_component = false;
};

/** What every block `From` can send is to the blocks beside it, as `To` has it, for a hop that gives
 * blocks states. */
template <int From, int To>
std::span<const NeighborBlock> getNeighborBlocks();

/** The record of the block `To` calls `id`, or null for a block `From` cannot send, such as an
 * add-on's. */
template <int From, int To>
const NeighborBlock *findNeighborBlock(std::uint32_t id)
{
    static const auto blocks = [] {
        std::vector<std::pair<std::uint32_t, const NeighborBlock *>> result;
        for (const auto &block : getNeighborBlocks<From, To>()) {
            forEachState(parseSnbt<bp::CompoundTag>(block.states), [&](const bp::CompoundTag &states) {
                result.emplace_back(computeRawSerializationIdHashForNetwork(block.name, states), &block);
            });
        }
        std::ranges::sort(result);
        return result;
    }();
    const auto it = std::ranges::lower_bound(blocks, id, {}, &std::pair<std::uint32_t, const NeighborBlock *>::first);
    return it != blocks.end() && it->first == id ? it->second : nullptr;
}

/** The blocks of the types a hop gives `states`, with the id each takes for every way of setting them:
 * way `w` gives `states[i]` the value `values[w / values.size()^i % values.size()]`. */
class ConnectedBlocks {
public:
    template <class Select>
    ConnectedBlocks(std::span<const BlockStateUpdate> updates, Select &&select, std::vector<std::string_view> states,
                    std::vector<bp::Tag> values)
    {
        for (std::size_t i = 0; i < states.size(); ++i) {
            ways_ *= values.size();
        }
        for (const auto &update : updates) {
            if (!select(update)) {
                continue;
            }
            const auto name = update.rename.empty() ? update.name : update.rename;
            forEachBlock(update, [&](const bp::CompoundTag &, const bp::CompoundTag &updated) {
                const auto first = ids_.size();
                for (std::size_t way = 0; way < ways_; ++way) {
                    bp::CompoundTag block = updated;
                    for (std::size_t i = 0, digits = way; i < states.size(); ++i, digits /= values.size()) {
                        block.insert_or_assign(std::string(states[i]), values[digits % values.size()]);
                    }
                    ids_.push_back(computeRawSerializationIdHashForNetwork(name, block));
                }
                for (auto i = first; i < ids_.size(); ++i) {
                    index_.emplace_back(ids_[i], first);
                }
            });
        }
        std::ranges::sort(index_);
    }

    /** The ids, by way, of the block `id` is one of, or none for a block the hop leaves alone. */
    [[nodiscard]] std::span<const std::uint32_t> find(std::uint32_t id) const
    {
        const auto it = std::ranges::lower_bound(index_, id, {}, &std::pair<std::uint32_t, std::size_t>::first);
        if (it == index_.end() || it->first != id) {
            return {};
        }
        return std::span{ids_}.subspan(it->second, ways_);
    }

private:
    std::size_t ways_ = 1;
    std::vector<std::uint32_t> ids_;
    std::vector<std::pair<std::uint32_t, std::size_t>> index_;
};

/** The states a hop adds that BDS works out from the blocks around them. A hop that adds any
 * specialises it with `connects(id)`, and `connect(pos, id, get)`, which gives the id the block at
 * `pos` takes from its neighbours, read through `get(pos)`.
 * @see ViaVersion ConnectionData. */
template <int From, int To>
struct ConnectionData {};

template <int From, int To>
concept HasConnections = requires(std::uint32_t id) { ConnectionData<From, To>::connects(id); };

/** `pos` moved by `offset`. */
inline bp::BlockPos offsetPos(const bp::BlockPos &pos, const bp::BlockPos &offset)
{
    return {pos.x + offset.x, pos.y + offset.y, pos.z + offset.z};
}

