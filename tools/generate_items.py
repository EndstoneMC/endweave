"""Generates each hop's item mappings from the item names in data/.

A hop whose source version has items its target lacks gets an item_mappings.h listing their names,
sorted: the items the target has no mapping for. No other hop gets one.

Usage: uv run tools/generate_items.py
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data"
PROTOCOLS = ROOT / "src" / "endweave" / "protocols"


class ItemList:
    """One version's item names, read from data/v<protocol>.json."""

    def __init__(self, protocol: int, mapping: dict) -> None:
        self.protocol = protocol
        self.version = mapping["version"]
        self.names = set(mapping["items"])


def write_hop(source: ItemList, target: ItemList) -> None:
    missing = sorted(source.names - target.names)
    if not missing:
        return
    path = PROTOCOLS / f"v{source.protocol}_to_v{target.protocol}" / "item_mappings.h"
    lines = [
        "// clang-format off",
        f"// Generated by tools/generate_items.py from data/v{source.protocol}.json ({source.version}) and",
        f"// data/v{target.protocol}.json ({target.version}).",
        "",
        "#pragma once",
        "",
        '#include "endweave/protocol/mapping.h"',
        "",
        "#include <array>",
        "#include <span>",
        "#include <string_view>",
        "",
        "namespace endweave {",
        "",
        "template <>",
        f"struct ItemMappings<{source.protocol}, {target.protocol}> {{",
        "    static std::span<const std::string_view> get()",
        "    {",
        f"        static constexpr std::array<std::string_view, {len(missing)}> names = {{{{",
        *(f'            "{name}",' for name in missing),
        "        }};",
        "        return names;",
        "    }",
        "};",
        "",
        "} // namespace endweave",
        "",
    ]
    path.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"{path.relative_to(ROOT)}: {len(missing)} items")


def main() -> None:
    if len(sys.argv) != 1:
        sys.exit(__doc__)
    lists = sorted(
        (
            ItemList(int(path.stem.removeprefix("v")), json.loads(path.read_text(encoding="utf-8")))
            for path in DATA.glob("v*.json")
        ),
        key=lambda items: items.protocol,
    )
    for older, newer in zip(lists, lists[1:]):
        write_hop(older, newer)
        write_hop(newer, older)


if __name__ == "__main__":
    main()
